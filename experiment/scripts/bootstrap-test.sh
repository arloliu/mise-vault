#!/usr/bin/env bash
# End-to-end bootstrap test: the full new-developer flow
# in a fresh isolated HOME, driven only by git clone + ~/.netrc.
#
# The MAIN flow (phases 1-5) bootstraps from the experiment GitLab's default
# branch, which must equal the local HEAD — so every assertion about machine
# state is made against the code under review, never against an older tag.
# Phase 6 separately proves that a tag-pinned bootstrap works, in its own HOME.
set -uo pipefail

GITLAB=http://127.0.0.3:8929
NEXUS=http://127.0.0.2:8081
PIN_REF=v0.0.14              # any known-good experiment tag; used for pin/re-pin coverage only

T=$(mktemp -d /tmp/mise-vault-bootstrap.XXXXXX)
PASS=0; FAIL=0
ok()  { PASS=$((PASS+1)); printf '  PASS  %s\n' "$1"; }
bad() { FAIL=$((FAIL+1)); printf '  FAIL  %s\n' "$1"; }

write_netrc() { # write_netrc <home>
  cat > "$1/.netrc" <<NETRC
machine 127.0.0.3
  login developer
  password glpat-mise-vault-dev-000001
machine 127.0.0.2
  login developer
  password dev-mise-vault
NETRC
  chmod 600 "$1/.netrc"
}

export HOME="$T"
unset MISE_DATA_DIR MISE_CONFIG_DIR MISE_CACHE_DIR MISE_STATE_DIR MISE_GLOBAL_CONFIG_FILE 2>/dev/null
write_netrc "$T"

echo "== 1. documented bootstrap from the default branch (the code under review) =="
REPO_ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)
LOCAL_HEAD=$(git -C "$REPO_ROOT" rev-parse HEAD 2>/dev/null || echo unknown)
rm -rf "$T/bootstrap"
GIT_TERMINAL_PROMPT=0 git clone -q --depth 1 "$GITLAB/devtools/mise-vault.git" "$T/bootstrap" \
  && ok "git clone (default branch) via netrc" || bad "git clone failed"
CLONED=$(git -C "$T/bootstrap" rev-parse HEAD 2>/dev/null || echo none)
# everything below only vouches for the code under review if this holds
[ "$CLONED" = "$LOCAL_HEAD" ] \
  && ok "experiment GitLab default branch == local HEAD ($(echo $LOCAL_HEAD | head -c 12))" \
  || bad "experiment GitLab is NOT serving the local HEAD (cloned $(echo $CLONED | head -c 12), local $(echo $LOCAL_HEAD | head -c 12)) — push to the experiment remote and re-run"
EXPECT=$(git -C "$T/bootstrap" describe --tags --exact-match 2>/dev/null || echo "$CLONED")
"$T/bootstrap/install.sh" > "$T/install1.log" 2>&1 \
  && ok "./install.sh (branch checkout installs the exact cloned commit)" \
  || bad "install.sh failed (log: $(tail -2 "$T/install1.log" | head -c 200))"
grep -q "version $EXPECT" "$T/install1.log" \
  && ok "installer self-detected the cloned commit ($(echo $EXPECT | head -c 12))" \
  || bad "commit self-detection (log: $(grep -i version "$T/install1.log" | head -1 | head -c 120))"
# token-based alternative fetch must also serve the script intact
RAW=$(curl -fsSL -H "PRIVATE-TOKEN: glpat-mise-vault-dev-000001" \
    "$GITLAB/api/v4/projects/devtools%2Fmise-vault/repository/files/install.sh/raw?ref=$CLONED" || true)
printf '%s' "$RAW" | head -1 | grep -q '#!/usr/bin/env bash' \
  && ok "API+PRIVATE-TOKEN raw fetch returns the script" \
  || bad "API raw fetch alternative"

echo "== 2. resulting machine state =="
mise settings gix 2>/dev/null | grep -q false && ok "settings gix=false written" || bad "gix setting"
# both must be false — either one being true selects mise's built-in git,
# which ignores netrc and credential helpers
mise settings libgit2 2>/dev/null | grep -q false && ok "settings libgit2=false written" || bad "libgit2 setting"
mise settings disable_default_registry 2>/dev/null | grep -q true \
  && ok "settings disable_default_registry=true written" || bad "disable_default_registry setting"
DB=$(mise settings disable_backends 2>/dev/null)
echo "$DB" | grep -q core && echo "$DB" | grep -q aqua \
  && ok "disable_backends covers the public backends (core, aqua, ...)" \
  || bad "disable_backends incomplete (got: $(echo $DB | head -c 120))"
grep -q 'GENERATED by mise-vault' "$T/.config/mise/conf.d/mise-vault.toml" 2>/dev/null \
  && ok "conf.d/mise-vault.toml generated" || bad "conf.d file"
grep -q "^glab = 'vault:glab'$" "$T/.config/mise/conf.d/mise-vault.toml" 2>/dev/null \
  && ok "aliases are pure routing (no embedded URL)" || bad "alias shape"

echo "== 3. developer experience =="
LSR=$(mise ls-remote golangci-lint 2>/dev/null)
[ "$(echo $LSR)" = "2.12.1 2.12.2" ] && ok "mise ls-remote golangci-lint == catalog" || bad "ls-remote (got: $(echo $LSR))"
PROJ="$T/app"; mkdir -p "$PROJ"
printf '[tools]\nglab = "1.113.0"\n' > "$PROJ/mise.toml"
(cd "$PROJ" && mise trust -q 2>/dev/null; mise install >/dev/null 2>&1 && mise exec -- glab --version 2>/dev/null | grep -qi 1.113.0) \
  && ok "project mise.toml -> mise install -> glab runs" || bad "project install flow"
# guard against the public-registry fallback false positive: backend must be ours
(cd "$PROJ" && mise tool glab 2>/dev/null | grep -q "vault:glab") \
  && ok "glab resolved through vault backend (not public registry)" \
  || bad "glab backend is NOT vault ($(cd "$PROJ" && mise tool glab 2>/dev/null | grep -i backend | head -1))"
# catalog-only policy: uncataloged names and explicit public backends must fail
JQOUT=$(timeout 30 mise ls-remote jq 2>&1 || true)
echo "$JQOUT" | grep -q "none of its backends" \
  && ok "uncataloged tool (jq) blocked — no public registry reach" \
  || bad "jq was not blocked ($(echo $JQOUT | head -c 100))"
AQOUT=$(timeout 30 mise install aqua:jqlang/jq@1.7.1 2>&1 || true)
echo "$AQOUT" | grep -q "disabled by disable_backends" \
  && ok "explicit public backend spec refused" \
  || bad "aqua: spec was not refused ($(echo $AQOUT | head -c 100))"

echo "== 4. idempotency: run the bootstrap again =="
"$T/bootstrap/install.sh" > "$T/install2.log" 2>&1 \
  && ok "second bootstrap run exits 0" || bad "second run (log: $(tail -2 "$T/install2.log" | head -c 200))"
mise ls-remote glab 2>/dev/null | grep -qx 1.113.0 && ok "still functional after re-run" || bad "post re-run state"

echo "== 5. vault-sync task (pin to a tag, then back to latest) =="
rm -f "$T/.config/mise/conf.d/mise-vault.toml"
"$T/.local/share/mise/plugins/vault/scripts/vault-sync" >/dev/null 2>&1 \
  && grep -q tool_alias "$T/.config/mise/conf.d/mise-vault.toml" 2>/dev/null \
  && ok "direct vault-sync regenerates deleted conf.d" || bad "direct vault-sync"
(cd "$T" && mise run vault-sync >/dev/null 2>&1) \
  && ok "'mise run vault-sync' works as a global task" || bad "mise run vault-sync (global task)"
(cd "$T" && mise run vault-sync "$PIN_REF" > "$T/sync-ref.log" 2>&1) \
  && grep -q "updating plugin to $PIN_REF" "$T/sync-ref.log" \
  && ok "'mise run vault-sync <ref>' re-pins plugin then regenerates" \
  || bad "vault-sync with ref (log: $(tail -2 "$T/sync-ref.log" 2>/dev/null | head -c 200))"
(cd "$T" && mise run vault-sync latest > "$T/sync-latest.log" 2>&1) \
  && grep -q "updating plugin to latest" "$T/sync-latest.log" \
  && mise ls-remote glab 2>/dev/null | grep -qx 1.113.0 \
  && ok "'mise run vault-sync latest' updates to default-branch HEAD" \
  || bad "vault-sync latest (log: $(tail -2 "$T/sync-latest.log" 2>/dev/null | head -c 200))"

echo "== 6. tag-pinned bootstrap works too (separate HOME) =="
T4=$(mktemp -d /tmp/mise-vault-bootstrap-tag.XXXXXX)
write_netrc "$T4"
HOME="$T4" bash -c '
  GIT_TERMINAL_PROMPT=0 git -c advice.detachedHead=false clone -q --depth 1 -b "'"$PIN_REF"'" \
    "'"$GITLAB"'/devtools/mise-vault.git" "$HOME/bootstrap" || exit 2
  "$HOME/bootstrap/install.sh" > "$HOME/install-tag.log" 2>&1 || exit 3
  grep -q "'"$PIN_REF"'" "$HOME/install-tag.log" || exit 4
  LSR=$(mise ls-remote glab 2>/dev/null); [ -n "$LSR" ] || exit 5
'
case $? in
  0) ok "tagged checkout ($PIN_REF) bootstraps, self-detects the tag, and serves the catalog" ;;
  2) bad "tag clone failed" ;;
  3) bad "tagged install.sh failed (log: $(tail -2 "$T4/install-tag.log" 2>/dev/null | head -c 200))" ;;
  4) bad "tag self-detection missing from install log" ;;
  *) bad "tagged bootstrap not functional" ;;
esac
rm -rf "$T4"

echo
echo "RESULT: $PASS passed, $FAIL failed   (HOME: $T — kept on failure)"
[ "$FAIL" = 0 ] && rm -rf "$T"
exit $([ "$FAIL" = 0 ] && echo 0 || echo 1)
